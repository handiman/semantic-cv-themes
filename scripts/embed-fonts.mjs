// Development tool, not part of the build. Downloads the web fonts of the themes that have one from
// Google Fonts and writes them into the CSS of the theme as base64 @font-face rules, so that a
// rendered CV loads nothing from the network for its fonts. The result is committed; run this again
// only to change which fonts or subsets a theme has.
//
//   node scripts/embed-fonts.mjs [theme ...]
//
// The fonts are licensed under the SIL Open Font License and the Apache License; see
// THIRD-PARTY-NOTICES.md.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

// Google Fonts sends woff2 files to a current browser.
const USER_AGENT =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

// A subset is a range of characters that Google serves as a file of its own. "latin" has the
// letters of Swedish and English; "latin-ext" has those of Polish and Czech, for example. The Noto
// fonts are large in latin-ext (about 165 kB each), so Lena has only latin.
const fonts = {
  gnap: [
    {
      family: "Open Sans",
      query: "Open+Sans:wght@300..800",
      weight: "300 800",
      subsets: ["latin", "latin-ext"]
    }
  ],
  lena: [
    { family: "Noto Sans", query: "Noto+Sans:wght@100..900", weight: "100 900", subsets: ["latin"] },
    {
      family: "Noto Sans Display",
      query: "Noto+Sans+Display:wght@100..900",
      weight: "100 900",
      subsets: ["latin"]
    }
  ],
  times: [
    { family: "Pirata One", query: "Pirata+One", weight: "400", subsets: ["latin", "latin-ext"] }
  ],
  typewriter: [
    { family: "Special Elite", query: "Special+Elite", weight: "400", subsets: ["latin", "latin-ext"] }
  ]
};

const START = "/* embedded fonts, generated by scripts/embed-fonts.mjs: start */";
const END = "/* embedded fonts, generated by scripts/embed-fonts.mjs: end */";

const get = async (url, as) => {
  const response = await fetch(url, { headers: { "User-Agent": USER_AGENT } });
  if (!response.ok) {
    throw new Error(`${url}: ${response.status}`);
  }
  return as === "text" ? response.text() : Buffer.from(await response.arrayBuffer());
};

/** The @font-face rules for one font: one per subset, with the font file inside the rule. */
const fontFaces = async ({ family, query, weight, subsets }) => {
  const css = await get(`https://fonts.googleapis.com/css2?family=${query}&display=swap`, "text");
  const blocks = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([^}]*)\}/g)];
  const rules = [];
  for (const subset of subsets) {
    const block = blocks.find(([, name]) => name === subset);
    if (!block) {
      throw new Error(`${family}: Google has no ${subset} subset`);
    }
    const body = block[2];
    const url = /url\((https:[^)]+)\)/.exec(body)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
    const stretch = /font-stretch:\s*([^;]+);/.exec(body)?.[1];
    if (!url || !range || /font-style:\s*italic/.test(body)) {
      throw new Error(`${family} ${subset}: unexpected CSS from Google`);
    }
    const file = await get(url, "binary");
    if (file.subarray(0, 4).toString("latin1") !== "wOF2") {
      throw new Error(`${family} ${subset}: not a woff2 file`);
    }
    const sha = crypto.createHash("sha256").update(file).digest("hex").slice(0, 12);
    rules.push(
      [
        `/* ${family}, ${subset}, sha256 ${sha} */`,
        "@font-face {",
        `  font-family: "${family}";`,
        "  font-style: normal;",
        `  font-weight: ${weight};`,
        ...(stretch ? [`  font-stretch: ${stretch};`] : []),
        `  src: url(data:font/woff2;base64,${file.toString("base64")}) format("woff2");`,
        `  unicode-range: ${range};`,
        "}"
      ].join("\n")
    );
  }
  return rules;
};

const themes = process.argv.length > 2 ? process.argv.slice(2) : Object.keys(fonts);
for (const theme of themes) {
  if (!fonts[theme]) {
    throw new Error(`${theme} has no fonts to embed; known: ${Object.keys(fonts).join(", ")}`);
  }
}

// Download everything before anything is written, so that a failure leaves the CSS as it was.
const generated = {};
for (const theme of themes) {
  const rules = [];
  for (const font of fonts[theme]) {
    rules.push(...(await fontFaces(font)));
  }
  generated[theme] = [START, ...rules, END].join("\n");
}

for (const theme of themes) {
  const file = path.join(import.meta.dirname, "..", theme, `${theme}.css`);
  const original = fs.readFileSync(file, "utf8");
  const eol = original.includes("\r\n") ? "\r\n" : "\n";
  const text = original.replace(/\r\n/g, "\n");
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  const updated =
    start >= 0 && end > start
      ? text.slice(0, start) + generated[theme] + text.slice(end + END.length)
      : `${generated[theme]}\n\n${text}`;
  fs.writeFileSync(file, updated.replace(/\n/g, eol));
  console.log(`${theme}: ${fonts[theme].map((font) => font.family).join(", ")}`);
}
